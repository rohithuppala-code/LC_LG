"""Pydantic models defining strict schemas for LLM extraction."""

from typing import List, Literal, Optional
from pydantic import BaseModel, Field


class KeyInsight(BaseModel):
    """A granular finding or data point extracted from research."""

    category: str = Field(
        ...,
        description="The thematic category of this insight, e.g., 'Technical', 'Financial', 'Risk', 'Market'.",
    )
    summary: str = Field(
        ...,
        description="A concise 1-2 sentence explanation of the specific insight.",
    )
    impact_level: Literal["low", "medium", "high", "critical"] = Field(
        default="medium",
        description="Assessed severity or strategic impact.",
    )
    confidence_score: float = Field(
        default=0.9,
        ge=0.0,
        le=1.0,
        description="Confidence score between 0.0 (unverified) and 1.0 (authoritative).",
    )


class ResearchReport(BaseModel):
    """A complete, structured synthesis generated by the research chain."""

    topic: str = Field(..., description="The subject or question analyzed.")
    executive_summary: str = Field(
        ...,
        description="High-level synthesis summarizing findings for executive review (100-250 words).",
    )
    key_insights: List[KeyInsight] = Field(
        default_factory=list,
        description="Categorized key insights and takeaways.",
    )
    pros: List[str] = Field(
        default_factory=list,
        description="Advantages, opportunities, or supporting evidence.",
    )
    cons: List[str] = Field(
        default_factory=list,
        description="Risks, drawbacks, limitations, or counterarguments.",
    )
    action_items: List[str] = Field(
        default_factory=list,
        description="Concrete, actionable recommendations or next steps.",
    )
    verdict: str = Field(
        ...,
        description="Final strategic verdict or takeaway decision.",
    )


class FactCheckResult(BaseModel):
    """Validation report for checking the veracity of a specific claim."""

    claim: str = Field(..., description="The original claim evaluated.")
    verdict: Literal["verified_true", "partially_true", "false", "unverifiable"] = (
        Field(..., description="The factual determination.")
    )
    confidence: float = Field(
        ..., ge=0.0, le=1.0, description="Confidence in the verification."
    )
    evidence: str = Field(..., description="Detailed explanation of the findings.")
    counter_evidence: Optional[str] = Field(
        default=None, description="Conflicting evidence if claim is disputed."
    )


class ActionPlan(BaseModel):
    """Step-by-step prioritized plan generated from an inquiry."""

    goal: str = Field(..., description="The ultimate target objective.")
    estimated_duration: str = Field(..., description="Expected timeframe, e.g. '2 weeks'.")
    steps: List[str] = Field(..., description="Sequential steps ordered by execution priority.")
    potential_bottlenecks: List[str] = Field(
        default_factory=list, description="Anticipated obstacles."
    )
